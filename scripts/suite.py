#!/usr/bin/env python3
"""Keep the suite marketplace loadable by every agent.

Source of truth (hand-edited):
  .claude-plugin/marketplace.json            read natively by Claude Code and Codex
  plugins/<name>/.claude-plugin/plugin.json

Generated by `sync` (never hand-edit):
  plugins/<name>/plugin.json                 Agent Plugins 1.0.0 manifest (Cursor and other agent-plugins.org clients)
  .cursor-plugin/marketplace.json            Cursor's multi-plugin index

Usage:
  python3 scripts/suite.py new <plugin> [--skill NAME] [--description TEXT]
  python3 scripts/suite.py sync
  python3 scripts/suite.py check             exit 1 on stale generated files or malformed skills
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
CURSOR_MARKETPLACE = ROOT / ".cursor-plugin" / "marketplace.json"
AGENT_PLUGINS_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
AGENT_PLUGINS_FIELDS = ("name", "version", "description", "author", "homepage", "repository", "license", "keywords")
AUTHOR_FIELDS = ("name", "email", "url")
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)

SKILL_TEMPLATE = """---
name: {skill}
description: TODO what this does, then "Use when ..." with the phrases and situations that should trigger it.
---

# {title}

TODO instructions. Name actions ("read the file", "run the tests"), not one agent's tool names, so every agent can follow them.
"""


def read_json(path: Path) -> dict:
    return json.loads(path.read_text())


def dump(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def local_plugins(marketplace: dict) -> list[tuple[dict, Path]]:
    """Marketplace entries whose source lives in this repo; remote sources ship their own manifests."""
    return [(entry, (ROOT / entry["source"]).resolve()) for entry in marketplace["plugins"] if isinstance(entry["source"], str)]


def agent_plugin_manifest(manifest: dict) -> dict:
    out = {"$schema": AGENT_PLUGINS_SCHEMA}
    for field in AGENT_PLUGINS_FIELDS:
        if field in manifest:
            out[field] = manifest[field]
    if "author" in out:
        out["author"] = {k: v for k, v in out["author"].items() if k in AUTHOR_FIELDS}
    return out


def cursor_marketplace(marketplace: dict) -> dict:
    out = {k: marketplace[k] for k in ("name", "owner", "description", "metadata") if k in marketplace}
    out["plugins"] = [
        {k: entry[k] for k in ("name", "source", "description") if k in entry}
        for entry, directory in local_plugins(marketplace)
        if is_portable(directory)
    ]
    return out


def is_portable(directory: Path) -> bool:
    """True when the plugin is only skills and MCP servers, all that Agent Plugins carries.

    A root plugin.json on a plugin with commands, hooks, or agents makes Codex load it as an Agent Plugin and drop those parts,
    so such plugins stay Claude Code/Codex-only.
    """
    has_portable = (directory / "skills").is_dir() or (directory / "mcp.json").is_file() or (directory / ".mcp.json").is_file()
    has_claude_only = any((directory / d).exists() for d in ("commands", "hooks", "agents"))
    return has_portable and not has_claude_only


def expected_files() -> dict[Path, str | None]:
    """Generated path → content, or None where a previously generated file must not exist."""
    marketplace = read_json(MARKETPLACE)
    files: dict[Path, str | None] = {CURSOR_MARKETPLACE: dump(cursor_marketplace(marketplace))}
    for _, directory in local_plugins(marketplace):
        manifest = read_json(directory / ".claude-plugin" / "plugin.json")
        files[directory / "plugin.json"] = dump(agent_plugin_manifest(manifest)) if is_portable(directory) else None
    return files


def is_stale(path: Path, content: str | None) -> bool:
    if content is None:
        return path.exists()
    return not path.exists() or path.read_text() != content


def manifest_errors() -> list[str]:
    marketplace = read_json(MARKETPLACE)
    errors = []
    listed = set()
    for entry, directory in local_plugins(marketplace):
        listed.add(directory.name)
        manifest = directory / ".claude-plugin" / "plugin.json"
        if not manifest.is_file():
            errors.append(f"{entry['name']}: {manifest.relative_to(ROOT)} missing")
        elif read_json(manifest)["name"] != entry["name"]:
            errors.append(f"{entry['name']}: plugin.json name differs from its marketplace entry")
    for entry in marketplace["plugins"]:
        source = entry["source"]
        if isinstance(source, dict) and source.get("source") == "github":
            errors.append(f"{entry['name']}: 'github' sources are invisible to Codex; use {{'source': 'url', 'url': 'https://github.com/<repo>.git'}}")
        if isinstance(source, str) and "version" in entry:
            errors.append(f"{entry['name']}: own plugins are never pinned; drop version from its marketplace entry")
        if isinstance(source, dict) and "version" in entry:
            errors.append(f"{entry['name']}: pin an external plugin with sha on its source, not version")
    for _, directory in local_plugins(marketplace):
        manifest = directory / ".claude-plugin" / "plugin.json"
        if manifest.is_file() and "version" in read_json(manifest):
            errors.append(f"{manifest.relative_to(ROOT)}: has a version, which freezes autoUpdate until bumped; remove it")
    for directory in sorted(p for p in (ROOT / "plugins").iterdir() if p.is_dir()):
        if directory.name not in listed:
            errors.append(f"plugins/{directory.name}: not listed in .claude-plugin/marketplace.json")
    return errors


def skill_errors() -> list[str]:
    """Agent Skills rules every agent enforces: frontmatter whose name equals the directory, plus a description."""
    errors = []
    for skill_md in sorted(ROOT.glob("plugins/*/skills/*/SKILL.md")):
        rel = skill_md.relative_to(ROOT)
        text = skill_md.read_text()
        match = FRONTMATTER_RE.match(text)
        if not match:
            errors.append(f"{rel}: missing YAML frontmatter")
            continue
        fields = dict(line.split(":", 1) for line in match.group(1).splitlines() if ":" in line and not line[0].isspace())
        name = fields.get("name", "").strip()
        if name != skill_md.parent.name:
            errors.append(f"{rel}: name '{name}' must equal directory '{skill_md.parent.name}'")
        if not fields.get("description", "").strip():
            errors.append(f"{rel}: missing description")
        if "TODO" in text:
            errors.append(f"{rel}: still has TODO placeholders")
    return errors


def cmd_sync(_: argparse.Namespace) -> int:
    for path, content in expected_files().items():
        if not is_stale(path, content):
            continue
        if content is None:
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


def cmd_check(_: argparse.Namespace) -> int:
    errors = manifest_errors()
    if not errors:
        stale = [p for p, content in expected_files().items() if is_stale(p, content)]
        errors += [f"{p.relative_to(ROOT)}: stale, run `python3 scripts/suite.py sync`" for p in stale]
    errors += skill_errors()
    for error in errors:
        print(error, file=sys.stderr)
    print("ok" if not errors else f"{len(errors)} problem(s)")
    return 1 if errors else 0


def cmd_new(args: argparse.Namespace) -> int:
    name = args.plugin
    if not NAME_RE.match(name):
        sys.exit(f"plugin name must be kebab-case: {name}")
    directory = ROOT / "plugins" / name
    if directory.exists():
        sys.exit(f"plugins/{name} already exists")
    marketplace = read_json(MARKETPLACE)
    skill = args.skill or name
    (directory / "skills" / skill).mkdir(parents=True)
    (directory / "skills" / skill / "SKILL.md").write_text(SKILL_TEMPLATE.format(skill=skill, title=skill.replace("-", " ").capitalize()))
    (directory / ".claude-plugin").mkdir()
    manifest = {"name": name, "description": args.description, "author": marketplace["owner"]}
    (directory / ".claude-plugin" / "plugin.json").write_text(dump(manifest))
    marketplace["plugins"].append({"name": name, "source": f"./plugins/{name}", "description": args.description})
    MARKETPLACE.write_text(dump(marketplace))
    print(f"created plugins/{name}; write plugins/{name}/skills/{skill}/SKILL.md")
    return cmd_sync(args)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    new = sub.add_parser("new", help="scaffold a plugin with one skill and register it")
    new.add_argument("plugin")
    new.add_argument("--skill", help="first skill's name (default: the plugin name)")
    new.add_argument("--description", default="TODO describe this plugin")
    new.set_defaults(func=cmd_new)
    sub.add_parser("sync", help="regenerate Agent Plugins and Cursor manifests").set_defaults(func=cmd_sync)
    sub.add_parser("check", help="fail on stale manifests or malformed skills").set_defaults(func=cmd_check)
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
